"""gen_prov.py <outdir> <stock.ko>... : stub providers (forged export CRCs) for every import of the given stock modules that is NOT exported by our kernel.
Providers are found among the OS4 stock modules (<work-dir>). One stub module per provider, containing only the needed symbols.
Writes <outdir>/prov_<mod>.c and <outdir>/BUILD.bazel (ddk_module prov_<mod>).  Runs on the build server."""
import glob, os, string, itertools, sys, zlib
sys.path.insert(0, "<work-dir>")
from crctool import exported, required

ALPHA = (string.ascii_letters + string.digits + "_").encode()
TAIL = b" { UNKNOWN } * ) "
Z = bytes(1)
base0 = zlib.crc32(b"x" + Z * 6 + TAIL)
TA = {}
for a in itertools.product(ALPHA, repeat=3):
    TA[zlib.crc32(b"x" + bytes(a) + Z * 3 + TAIL) ^ base0] = bytes(a)
GB = [(zlib.crc32(b"x" + Z * 3 + bytes(b) + TAIL) ^ base0, bytes(b)) for b in itertools.product(ALPHA, repeat=3)]


def forge(sym, target):
    pre = f"void {sym} ( struct fg".encode()
    base = zlib.crc32(pre + Z * 6 + TAIL)
    for g, b in GB:
        a = TA.get(target ^ base ^ g)
        if a is not None:
            return "fg" + (a + b).decode()
    raise SystemExit(f"no forge for {sym} {target:#x}")


out = sys.argv[1]
os.makedirs(out, exist_ok=True)
kern = {}
for l in open("<build-dir>"):
    p = l.split("\t")
    if len(p) > 2:
        kern[p[1]] = int(p[0], 16)
prov = {}  # symbol -> (module, crc)
for ko in glob.glob("<work-dir>"):
    try:
        for s, c in exported(ko).items():
            prov.setdefault(s, []).append((os.path.basename(ko)[:-3], c))
    except Exception:
        pass
need = {}  # module -> {sym: crc}
missing = []
for ko in sys.argv[2:]:
    for s, c in required(ko):
        if s == "module_layout":
            continue
        if s in kern:
            if kern[s] != c:
                print(f"KERNEL CRC MISMATCH {s} stock {c:#x} ours {kern[s]:#x}")
            continue
        cands = [m for m, cc in prov.get(s, []) if cc == c] or [m for m, cc in prov.get(s, [])]
        if not cands:
            missing.append(s)
            continue
        need.setdefault(cands[0], {})[s] = c
build = ['load("/<build-dir>", "ddk_module")', 'package(default_visibility = ["//visibility:public"])',
         "# generated by work/a17/g4/gen_prov.py: stub providers with the exact OS4 stock export CRCs", ""]
for mod, syms in sorted(need.items()):
    n = mod.replace("-", "_")
    lines = ["// SPDX-License-Identifier: GPL-2.0", f"/* generated stub of {mod} (OS4 stock): forged struct tags give the stock export CRCs */",
             "#include <linux/module.h>", 'MODULE_LICENSE("GPL");']
    for s, c in sorted(syms.items()):
        t = forge(s, c)
        lines += [f"struct {t};", f"void {s}(struct {t} *p) {{}}", f"EXPORT_SYMBOL({s});"]
    open(f"{out}/prov_{n}.c", "w").write("\n".join(lines) + "\n")
    build.append(f'ddk_module(name = "prov_{n}", srcs = ["prov_{n}.c"], out = "{mod}.ko", kernel_build = "//common:kernel_aarch64", deps = ["//common:all_headers_aarch64"])')
    print(f"{mod}: {len(syms)} symbols")
open(f"{out}/BUILD.bazel", "w").write("\n".join(build) + "\n")
print("missing providers:", missing)
