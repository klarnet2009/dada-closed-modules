"""genenums.py <out.h> <dump_dir>... : emit enums of the module-local BTF dumps that are (partly) missing from /tmp/g13a_inc (stubs + module headers)"""
import re, sys, glob
out = sys.argv[2]; dumps = sys.argv[3:]
hdr = ''
for f in glob.glob(sys.argv[1] + '/**/*.h', recursive=True):
    hdr += open(f, errors='replace').read() + '\n'
present = set(re.findall(r'\b[A-Za-z_][A-Za-z0-9_]*\b', hdr))
seen = {}
for d in dumps:
    t = open(d + '/btf_all.txt').read()
    for m in re.finditer(r'^enum (\w+) \{(.*?)\};', t, re.M):
        seen.setdefault(m.group(1), m.group(2))
res = ['/* SPDX-License-Identifier: GPL-2.0 */',
       '/* Generated by work/re/g13a_tools/genenums.py (G13a, 18.10.2026) from the module-local BTF of the OS4 stock mca_quick_wireless.ko / mca_basic_wireless.ko:',
       ' * enums (names and values authoritative) that no other header of the overlay defines.  Community-only charging source. */',
       '#ifndef __MCA_BTF_ENUMS_G13A_H__', '#define __MCA_BTF_ENUMS_G13A_H__', '']
for name, body in seen.items():
    items = [x.strip() for x in body.split(',') if x.strip()]
    names = [i.split('=')[0].strip() for i in items]
    miss = [i for i, n in zip(items, names) if n not in present]
    if not miss: continue
    if len(miss) == len(items):
        res.append('enum %s {\n%s\n};\n' % (name, '\n'.join('\t%s,' % i for i in items)))
    else:
        res.append('/* partial: enum %s exists in the overlay; the missing enumerators: */\nenum {\n%s\n};\n' % (name, '\n'.join('\t%s,' % i for i in miss)))
res.append('#endif')
open(out, 'w', newline='\n').write('\n'.join(res) + '\n')
print(len(seen), 'enums seen')
