"""forge_misc.py <outdir> sym=0xCRC ...: forged stub provider (one .c + BUILD.bazel) as gen_stubs.py does (void sym(struct fgXXXXXX *) with a tag that makes genksyms yield CRC). Run on the server."""
import os, sys, zlib, itertools, string

ALPHA = (string.ascii_letters + string.digits + "_").encode()
TAIL = b" { UNKNOWN } * ) "
Z = bytes(1)
base0 = zlib.crc32(b"x" + Z * 6 + TAIL)
TA = {}
for a in itertools.product(ALPHA, repeat=3):
    TA[zlib.crc32(b"x" + bytes(a) + Z * 3 + TAIL) ^ base0] = bytes(a)
GB = [(zlib.crc32(b"x" + Z * 3 + bytes(b) + TAIL) ^ base0, bytes(b)) for b in itertools.product(ALPHA, repeat=3)]


def forge(sym, target):
    pre = f"void {sym} ( struct fg".encode()
    base = zlib.crc32(pre + Z * 6 + TAIL)
    for g, b in GB:
        a = TA.get(target ^ base ^ g)
        if a is not None:
            assert zlib.crc32(pre + a + b + TAIL) == target
            return "fg" + (a + b).decode()
    raise SystemExit(f"no forge for {sym} {target:#x}")


out = sys.argv[1]
os.makedirs(out, exist_ok=True)
c = ['// SPDX-License-Identifier: GPL-2.0',
     '/* generated by g2g_tools/forge_misc.py: stub providers with the exact OS4 stock import CRCs (community-only, never flash) */',
     '#include <linux/module.h>', 'MODULE_LICENSE("GPL");']
for a in sys.argv[2:]:
    sym, crc = a.split('=')
    tag = forge(sym, int(crc, 16))
    c += [f'struct {tag};', f'void {sym}(struct {tag} *p) {{}}', f'EXPORT_SYMBOL({sym});']
# one provider module per symbol, named like the stock provider (modinfo depends= line)
PROV = {'fsa4480_switch_event': 'fsa4480-i2c', 'connector_antiburn_is_triggered': 'mca_connector_antiburn', 'lpd_is_charging_limit': 'mca_lpd_detect'}
build = ['load("/<build-dir>", "ddk_module")', 'package(default_visibility = ["//re:__subpackages__"])', '']
for a in sys.argv[2:]:
    sym, crc = a.split('=')
    tag = forge(sym, int(crc, 16))
    fn = 'stub_%s.c' % sym
    open(out + '/' + fn, 'w').write('\n'.join(c[:4] + ['struct %s;' % tag, 'void %s(struct %s *p) {}' % (sym, tag), 'EXPORT_SYMBOL(%s);' % sym]) + '\n')
    build.append('ddk_module(name = "st_%s", srcs = ["%s"], out = "%s.ko", kernel_build = "//common:kernel_aarch64", deps = ["//common:all_headers_aarch64"])' % (sym, fn, PROV[sym]))
open(out + '/BUILD.bazel', 'w').write('\n'.join(build) + '\n')
