"""gen_stubs.py <outdir> <os4 provider .ko>...
Writes one stub .c per provider module whose exports carry EXACTLY the CRCs of the OS4 stock provider, without knowing any prototype.
genksyms hashes `void <sym> ( struct <tag> { UNKNOWN } * ) ` (zlib.crc32 of that stream), so the stub declares
`void <sym>(struct fgXXXXXX *)` with a tag whose 6 free characters are forged (meet-in-the-middle over crc32 linearity) to hit the stock CRC.
Also writes BUILD.bazel (ddk_module os4_<mod> per stub). Runs on the build server (needs <build-dir>)."""
import os, sys, zlib, itertools, string
sys.path.insert(0, "<build-dir>")
from crctool import exported

ALPHA = (string.ascii_letters + string.digits + "_").encode()
TAIL = b" { UNKNOWN } * ) "
Z = bytes(1)
# contribution of 3 free bytes at the first / second half position of the 6-byte slot (independent of the prefix)
base0 = zlib.crc32(b"x" + Z * 6 + TAIL)
TA = {}
for a in itertools.product(ALPHA, repeat=3):
    TA[zlib.crc32(b"x" + bytes(a) + Z * 3 + TAIL) ^ base0] = bytes(a)
GB = [(zlib.crc32(b"x" + Z * 3 + bytes(b) + TAIL) ^ base0, bytes(b)) for b in itertools.product(ALPHA, repeat=3)]


def forge(sym, target):
    pre = f"void {sym} ( struct fg".encode()
    base = zlib.crc32(pre + Z * 6 + TAIL)
    for g, b in GB:
        a = TA.get(target ^ base ^ g)
        if a is not None:
            tag = (a + b).decode()
            assert zlib.crc32(pre + a + b + TAIL) == target
            return "fg" + tag
    raise SystemExit(f"no forge for {sym} {target:#x}")


out = sys.argv[1]
os.makedirs(out, exist_ok=True)
build = ['load("/<build-dir>", "ddk_module")',
         'package(default_visibility = ["//re:__subpackages__"])',
         '# generated by work/a17/portB/gen_stubs.py: stub providers with the exact OS4 stock export CRCs', '']
for ko in sys.argv[2:]:
    mod = os.path.basename(ko)[:-3]
    ex = exported(ko)  # name -> crc
    if not ex:
        continue
    lines = ["// SPDX-License-Identifier: GPL-2.0",
             f"/* generated: stub provider of {mod} (OS4 stock); the struct tags are forged so that genksyms yields the stock export CRCs */",
             "#include <linux/module.h>", 'MODULE_LICENSE("GPL");']
    for n, c in sorted(ex.items()):
        t = forge(n, c)
        lines += [f"struct {t};", f"void {n}(struct {t} *p) {{}}", f"EXPORT_SYMBOL({n});"]
    open(f"{out}/os4_{mod}.c", "w").write("\n".join(lines) + "\n")
    build.append(f'ddk_module(name = "os4_{mod}", srcs = ["os4_{mod}.c"], out = "os4_{mod}.ko", kernel_build = "//common:kernel_aarch64", '
                 f'deps = ["//common:all_headers_aarch64"])')
open(f"{out}/BUILD.bazel", "w").write("\n".join(build) + "\n")
print("stubs:", len(build) - 4)
