"""genhdr.py btf_mod.txt > matt_types.h : convert module-local matt_* struct definitions of the BTF dump into C (topologically sorted)."""
import re, sys

txt = open(sys.argv[1], encoding='utf8').read().split('\n')
want = set("""matt_hashinfo matt_shash_table matt_shash_head matt_uhash_table matt_uhash_head matt_sock matt_ulp_ops matt_request_sock
matt_sockaddr matt_src matt_addr matt_port matt_udp_sock matt_dst matt_cc_ctx matt_cc_ops matt_cc_info matt_bbr_info matt_input_ctx matt_sack_block
matt_stats matt_data_stats matt_output_ctx matt_rack matt_mgmt matt_timer_ctx matt_retrans_timer matt_pack_timer matt_nack_timer matt_ping_timer
matt_reo_timer matt_rto_timer matt_stats_timer category_name_info matthdr matt_skb_cb matt6_sock matt_info matt_creq matt_crsp matt_ping matt_pong
matt_rst matt_pack matt_sack_block_wire matt_nack matt_report matt_sacktag_state msq_tasklet matt_addr_family_ops matt_proto_family_ops symbol_entry""".split())
blocks = {}
i = 0
while i < len(txt):
    m = re.match(r'^(struct|union) (\w+) \{$', txt[i])
    if m and m.group(2) in want and m.group(2) not in blocks:
        j = i
        while not txt[j].startswith('}'):
            j += 1
        blocks[m.group(2)] = (m.group(1), txt[i + 1:j])
        i = j
    i += 1
missing = want - set(blocks)
if missing:
    sys.stderr.write('missing: %s\n' % missing)


def conv(line, bf_ok=True):
    # '\ttype name : N;\t/* +off */'  -> 'type name : N;'  (': 0' = plain member)
    l = re.sub(r'\t/\* \+\d+ \*/$', '', line)
    l = re.sub(r' : 0;$', ';', l)
    l = l.replace('? *', 'void *')
    l = re.sub(r'^(\s*)\}; /\* size \d+ \*/ ?(\w*) ?;$', lambda m: m.group(1) + '} ' + m.group(2) + ';' if m.group(2) else m.group(1) + '};', l)
    return l


def deps(name):
    d = set()
    for l in blocks[name][1]:
        if '(*' in l:
            continue
        m = re.match(r'^\s*(?:const )?(?:struct|union) (\w+) [^*]*;', l)
        if m and m.group(1) in blocks:
            d.add(m.group(1))
    return d


order, seen = [], set()


def visit(n):
    if n in seen:
        return
    seen.add(n)
    for d in sorted(deps(n)):
        visit(d)
    order.append(n)


for n in sorted(blocks):
    visit(n)
print('/* generated by g11_tools/genhdr.py from the BTF of the OS4 stock matt.ko (types of the module itself) */')
for n in order:
    kind, body = blocks[n]
    print('%s %s {' % (kind, n))
    for l in body:
        print(conv(l))
    print('};')
